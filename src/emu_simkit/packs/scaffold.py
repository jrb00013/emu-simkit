"""Create a new pack directory from a template."""

from __future__ import annotations

from pathlib import Path

from emu_simkit.errors import PackError
from emu_simkit.packs.manifest import save_manifest
from emu_simkit.types import PackManifest

_PATCH = """Version: 1.2

HASH-placeholder0000000000000000000000000000:
  "{name}: starter patch":
    Games:
      "Placeholder Title":
        {title}: [ 01.00 ]
    Author: "emu-simkit"
    Notes: |
      Starter patch — replace hash, addresses, and values before use.
    Patch Version: 1.0
    Patch:
      - [ be32, 0x00000000, 0x60000000 ]
"""

_OVERRIDES = """Core:
  Example Knob: true
"""

_PATCH_CONFIG = """HASH-placeholder0000000000000000000000000000:
  "{name}: starter patch":
    "Placeholder Title":
      {title}:
        "01.00":
          Enabled: true
"""


def scaffold_pack(
    dest: Path | str,
    *,
    name: str,
    title: str = "EXAMPLE00000",
    backend: str = "generic",
    force: bool = False,
) -> Path:
    dest = Path(dest)
    if dest.exists() and any(dest.iterdir()) and not force:
        raise PackError(f"destination not empty: {dest}")
    dest.mkdir(parents=True, exist_ok=True)
    patch_name = f"{name}_patch.yml"
    (dest / patch_name).write_text(
        _PATCH.format(name=name, title=title), encoding="utf-8"
    )
    (dest / "overrides.yml").write_text(_OVERRIDES, encoding="utf-8")
    (dest / "patch_config.yml").write_text(
        _PATCH_CONFIG.format(name=name, title=title), encoding="utf-8"
    )
    (dest / "README.md").write_text(
        f"# {name}\n\nGenerated by `emu-simkit pack init`.\n",
        encoding="utf-8",
    )
    manifest = PackManifest(
        name=name,
        version="0.1.0",
        description=f"Scaffolded pack {name}",
        backend=backend,
        titles=[title],
        patches=[patch_name],
        overrides=["overrides.yml"],
        patch_config="patch_config.yml",
    )
    save_manifest(dest / "pack.yml", manifest)
    return dest
